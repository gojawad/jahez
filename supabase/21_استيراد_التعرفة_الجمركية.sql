-- ---------- عمود جديد اختياري لنسبة الرسم الجمركي (نص، ليس رقم، لأنه قد يكون "0%" أو "5%") ----------
alter table public.commodities add column if not exists duty text;

-- ---------- فهرس تفرّد جزئي على hs_code، يُستخدم لمنع التكرار عند الاستيراد ----------
-- جزئي (يتجاهل القيم الفارغة/الفاضية) حتى لا يمنع إضافة سلع بدون HS Code كما كان ممكناً قبل هذا الملف.
create unique index if not exists commodities_hs_code_unique
  on public.commodities(hs_code)
  where hs_code is not null and hs_code <> '';

notify pgrst, 'reload schema';

