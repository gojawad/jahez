-- السبب: شاشة تسجيل الدخول نفسها (قبل أي مصادقة) تحتاج تعرض
-- الشعار وصورة الخلفية المرفوعين من لوحة التحكم. سياسة settings_read
-- الحالية تشترط تسجيل دخول لأي قراءة من جدول settings، فكانت شاشة
-- القفل تفشل في جلب الهوية على أي جهاز جديد قبل تسجيل الدخول.
--
-- هذه السياسة الإضافية تسمح بقراءة صف key='branding' تحديداً فقط
-- (الشعار، الألوان، صورة شاشة الدخول — بيانات غير حساسة أصلاً ومفروض
-- تظهر لأي زائر) بدون أي تسجيل دخول. بقية الإعدادات (بيانات الشركات،
-- أماكن الحقول، إلخ) تبقى محمية تماماً كما هي — سياسة settings_read
-- الأصلية لم تُمس.

drop policy if exists settings_read_branding_public on public.settings;
create policy settings_read_branding_public on public.settings
  for select to anon, authenticated
  using (key = 'branding');

notify pgrst, 'reload schema';
